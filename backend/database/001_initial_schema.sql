/* Baseline schema for a new local AzureGuard database. Safe to re-run; never drops data. */
IF OBJECT_ID(N'dbo.AppUsers', N'U') IS NULL CREATE TABLE dbo.AppUsers (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    FullName NVARCHAR(MAX) NOT NULL,
    Email NVARCHAR(450) NOT NULL,
    RoleName NVARCHAR(MAX) NOT NULL CONSTRAINT DF_AppUsers_RoleName DEFAULT ('Developer'),
    IsActive BIT NOT NULL CONSTRAINT DF_AppUsers_IsActive DEFAULT (1),
    PasswordHash NVARCHAR(500) NOT NULL,
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_AppUsers_CreatedAt DEFAULT (SYSUTCDATETIME())
);
IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE object_id = OBJECT_ID(N'dbo.AppUsers') AND name = N'IX_AppUsers_Email')
    CREATE UNIQUE INDEX IX_AppUsers_Email ON dbo.AppUsers(Email);

IF OBJECT_ID(N'dbo.Projects', N'U') IS NULL CREATE TABLE dbo.Projects (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, Name NVARCHAR(MAX) NOT NULL, Description NVARCHAR(MAX) NULL,
    RepositoryUrl NVARCHAR(MAX) NOT NULL, BranchName NVARCHAR(MAX) NOT NULL, TechStack NVARCHAR(MAX) NOT NULL,
    BuildCommand NVARCHAR(MAX) NULL, TestCommand NVARCHAR(MAX) NULL, DockerfilePath NVARCHAR(MAX) NOT NULL,
    HelmChartPath NVARCHAR(MAX) NULL, IsActive BIT NOT NULL, CreatedByUserId BIGINT NULL,
    CreatedAt DATETIME2 NOT NULL
);
IF OBJECT_ID(N'dbo.Releases', N'U') IS NULL CREATE TABLE dbo.Releases (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, ProjectId BIGINT NOT NULL, ReleaseVersion NVARCHAR(MAX) NOT NULL,
    CommitSha NVARCHAR(MAX) NULL, BranchName NVARCHAR(MAX) NOT NULL, TriggeredByUserId BIGINT NULL,
    Status NVARCHAR(MAX) NOT NULL, StartedAt DATETIME2 NULL, CompletedAt DATETIME2 NULL, CreatedAt DATETIME2 NOT NULL
);
IF OBJECT_ID(N'dbo.ScanResults', N'U') IS NULL CREATE TABLE dbo.ScanResults (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, ReleaseId BIGINT NOT NULL, ScanType NVARCHAR(MAX) NOT NULL,
    ToolName NVARCHAR(MAX) NOT NULL, Status NVARCHAR(MAX) NOT NULL, CriticalCount INT NOT NULL, HighCount INT NOT NULL,
    MediumCount INT NOT NULL, LowCount INT NOT NULL, InfoCount INT NOT NULL, RawSummaryJson NVARCHAR(MAX) NULL,
    ReportUrl NVARCHAR(MAX) NULL, CreatedAt DATETIME2 NOT NULL
);
IF OBJECT_ID(N'dbo.RiskScores', N'U') IS NULL CREATE TABLE dbo.RiskScores (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, ReleaseId BIGINT NOT NULL, ModelName NVARCHAR(MAX) NOT NULL,
    RiskScore DECIMAL(18,2) NOT NULL, RiskLevel NVARCHAR(MAX) NOT NULL, FeatureJson NVARCHAR(MAX) NULL,
    PredictionReason NVARCHAR(MAX) NULL, CreatedAt DATETIME2 NOT NULL
);
IF OBJECT_ID(N'dbo.PolicyDecisions', N'U') IS NULL CREATE TABLE dbo.PolicyDecisions (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, ReleaseId BIGINT NOT NULL, RiskScore DECIMAL(18,2) NOT NULL,
    Decision NVARCHAR(MAX) NOT NULL, DecisionReason NVARCHAR(MAX) NOT NULL, DecidedBy NVARCHAR(MAX) NOT NULL,
    DecidedAt DATETIME2 NOT NULL
);
IF OBJECT_ID(N'dbo.PipelineRuns', N'U') IS NULL CREATE TABLE dbo.PipelineRuns (
    Id BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY, ReleaseId BIGINT NOT NULL, Provider NVARCHAR(MAX) NOT NULL,
    ExternalRunId NVARCHAR(MAX) NULL, PipelineUrl NVARCHAR(MAX) NULL, Status NVARCHAR(MAX) NOT NULL,
    StartedAt DATETIME2 NULL, CompletedAt DATETIME2 NULL, ErrorMessage NVARCHAR(MAX) NULL, CreatedAt DATETIME2 NOT NULL
);
GO
